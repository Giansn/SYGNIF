def glyph(character: str) -> Optional[Sequence[str]]:
    """Bitmap rows for a character, or ``None`` if it has no glyph.

    Returning ``None`` rather than raising means an unexpected character
    leaves a gap instead of crashing the renderer. A missing glyph is a
    cosmetic problem; a crash in the draw call during a boss fight is not.
    """
    return GLYPHS.get(character.upper())


def text_width(message: str, scale: int = 1, spacing: int = 1) -> int:
    """Pixel width of ``message``, for centring and right-alignment."""
    if not message:
        return 0
    return len(message) * (GLYPH_WIDTH + spacing) * scale - spacing * scale


def validate() -> list[str]:
    """Check every glyph is exactly 5x7. Returns a list of problems."""
    problems = []
    for character, rows in GLYPHS.items():
        if len(rows) != GLYPH_HEIGHT:
            problems.append(f"{character!r}: {len(rows)} rows, expected {GLYPH_HEIGHT}")
        for index, row in enumerate(rows):
            if len(row) != GLYPH_WIDTH:
                problems.append(f"{character!r} row {index}: {len(row)} columns, expected {GLYPH_WIDTH}")
            illegal = set(row) - {"#", "."}
            if illegal:
                problems.append(f"{character!r} row {index}: illegal characters {illegal}")
    return problems
