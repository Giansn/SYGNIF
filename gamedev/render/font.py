"""A hand-authored 5x7 bitmap font.

A game needs text long before it needs a font library: score, timer, debug
overlays, the words "GAME OVER". Rasterising TrueType is a large problem;
drawing letters from a fixed grid of bits is a small one, and at low
resolution the fixed grid actually looks better because there is no hinting
or antialiasing to smear a 5-pixel-wide letter into grey mush.

The glyphs live as ASCII art so that the source is also the preview — editing
a letter means editing a picture of that letter. Five by seven is the
smallest grid on which the full uppercase alphabet stays unambiguous; at 5x5
the classic collisions are S/5, B/8 and O/0/Q.
"""

